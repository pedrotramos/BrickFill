import { createHash } from 'node:crypto';
import type { FilePolicy } from '@databricks/appkit';
import { z } from 'zod';
import { createEvidenceReadPolicy } from './evidence-policy';

export const MANUAL_EVIDENCE_VOLUME = 'manual_evidence';
export const MAX_SCREENSHOT_BYTES = 10 * 1024 * 1024;

export const ProductEan = z.string().regex(/^\d{8,14}$/);
/**
 * The canonical contract leaves attribute_id an unrestricted string (dots, slashes, spaces...), so any non-blank code
 * is accepted as is; the routes check it against the product's attributes, and {@link attributePathSegment} keeps it
 * out of screenshot paths.
 */
export const AttributeCode = z
  .string()
  .max(1000)
  .refine((value) => value.trim().length > 0);

const SAFE_SEGMENT = /^[A-Za-z0-9_-]{1,100}$/;

/**
 * The attribute's folder in the manual evidence Volume: the code itself when it is a plain identifier, otherwise "~"
 * and the SHA-256 of the code ("~" never appears in a plain one, so the two forms cannot collide).
 */
export function attributePathSegment(attributeCode: string): string {
  return SAFE_SEGMENT.test(attributeCode) ? attributeCode : `~${sha256(Buffer.from(attributeCode, 'utf8'))}`;
}

const IMAGE_TYPES = {
  png: 'image/png',
  jpg: 'image/jpeg',
  webp: 'image/webp',
} as const;
export type ImageExtension = keyof typeof IMAGE_TYPES;

/** Identify the image from its bytes; the declared content type and file name are never trusted. */
export function detectImage(content: Buffer): ImageExtension | undefined {
  if (
    content.length >= 8 &&
    content.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))
  )
    return 'png';
  if (content.length >= 3 && content[0] === 0xff && content[1] === 0xd8 && content[2] === 0xff) return 'jpg';
  if (
    content.length >= 12 &&
    content.subarray(0, 4).toString('ascii') === 'RIFF' &&
    content.subarray(8, 12).toString('ascii') === 'WEBP'
  )
    return 'webp';
  return undefined;
}

export function contentTypeOf(extension: ImageExtension): string {
  return IMAGE_TYPES[extension];
}

export function sha256(content: Buffer): string {
  return createHash('sha256').update(content).digest('hex');
}

/** Content-addressed location generated by the server: re-uploading the same image is idempotent. */
export function manualScreenshotPath(
  root: string,
  ean: string,
  attributeCode: string,
  digest: string,
  extension: ImageExtension
): string {
  return `${root}/manual/${ean}/${attributePathSegment(attributeCode)}/${digest}.${extension}`;
}

export interface ParsedScreenshotPath {
  sha256: string;
  contentType: string;
}

/** Accept only a path this server generated for the same product and attribute. */
export function parseManualScreenshotPath(
  root: string | undefined,
  path: string,
  ean: string,
  attributeCode: string
): ParsedScreenshotPath | undefined {
  if (!root) return undefined;
  const prefix = `${root}/manual/${ean}/${attributePathSegment(attributeCode)}/`;
  if (!path.startsWith(prefix)) return undefined;
  const match = /^([0-9a-f]{64})\.(png|jpg|webp)$/.exec(path.slice(prefix.length));
  if (!match) return undefined;
  return { sha256: match[1], contentType: contentTypeOf(match[2] as ImageExtension) };
}

const MANUAL_PATH =
  /^\/Volumes\/[^/]+\/[^/]+\/[^/]+\/manual\/\d{8,14}\/(?:[A-Za-z0-9_-]{1,100}|~[0-9a-f]{64})\/[0-9a-f]{64}\.(png|jpg|webp)$/;

/**
 * Reviewers read every manual screenshot; only the server itself (programmatic calls run as the app's service
 * principal) can write, and only to the content-addressed path it generates. Nothing is ever deleted.
 */
export function createManualEvidencePolicy(volumeRoot: string | undefined): FilePolicy {
  const read = createEvidenceReadPolicy(volumeRoot, MANUAL_EVIDENCE_VOLUME);
  const root = volumeRoot?.replace(/\/+$/, '');
  return (action, resource, user) => {
    if (action !== 'upload') return read(action, resource, user);
    return (
      Boolean(root) &&
      Boolean(user.isServicePrincipal) &&
      resource.volume === MANUAL_EVIDENCE_VOLUME &&
      resource.path.startsWith(`${root}/manual/`) &&
      MANUAL_PATH.test(resource.path)
    );
  };
}

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .optional()
    .transform((value) => (value ? value : undefined));

export const ManualEvidenceBody = z
  .object({
    sourceUrl: optionalText(2000).refine((value) => value === undefined || /^https:\/\/[^\s]+$/.test(value), {
      // The message is an error code (http-errors.ts) so the client can translate it.
      message: 'EVIDENCE_URL_NOT_HTTPS',
    }),
    excerpt: optionalText(2000),
    note: optionalText(2000),
    screenshotPath: optionalText(500),
  })
  .refine((value) => Boolean(value.screenshotPath) || Boolean(value.sourceUrl && value.excerpt), {
    message: 'EVIDENCE_MISSING',
  });
export type ManualEvidenceInput = z.infer<typeof ManualEvidenceBody>;
